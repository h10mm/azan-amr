    val categories: List<AzkarCategory> by lazy {
        AzkarCategoryId.entries.map { catId ->
            AzkarCategory(
                id = catId,
                items = allItems.filter { it.category == catId },
            )
        }
    }

    val dailyShortcutCategories: List<AzkarCategory> by lazy {
        categories.filter { it.id.isDailyShortcut }
    }

    fun getCategory(categoryId: String): AzkarCategory {
        val id = AzkarCategoryId.fromId(categoryId)
        return categories.first { it.id == id }
    }
