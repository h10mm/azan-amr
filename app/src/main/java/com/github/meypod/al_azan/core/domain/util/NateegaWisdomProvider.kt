    /**
     * يعيد حكمة اليوم بحيث يعاد ترتيب الـ 365 حكمة عشوائياً بشكل مختلف تماماً مع بداية كل عام جديد،
     * مع بقاء حكمة اليوم الواحد ثابتة طوال الـ 24 ساعة دون أي اضطراب أو تكرار.
     */
    fun getWisdomForDate(instant: Instant): String {
        val localDate = instant.toLocalDateTime(TimeZone.currentSystemDefault()).date
        val year = localDate.year
        val dayOfYear = localDate.dayOfYear

        val yearlyShuffled = getShuffledWisdomsForYear(year)
        val index = (dayOfYear - 1).coerceAtLeast(0) % yearlyShuffled.size
        return yearlyShuffled[index]
    }

    private fun getShuffledWisdomsForYear(year: Int): List<String> {
        val currentCache = cachedYearlyList
        if (cachedYear == year && currentCache.isNotEmpty()) {
            return currentCache
        }
        val shuffled = wisdoms.shuffled(Random(year))
        cachedYear = year
        cachedYearlyList = shuffled
        return shuffled
    }
